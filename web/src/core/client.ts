import { fromJson, toJson } from '@bufbuild/protobuf'
import { ValueSchema } from '@bufbuild/protobuf/wkt'
import { Code, ConnectError, createClient } from '@connectrpc/connect'
import { createConnectTransport } from '@connectrpc/connect-web'
import { AssistService, ConfigService, CoreService } from '../gen/haro/v1/haro_pb'
import type { Analysis, ApplyResult, AssistDone, AssistEvent, AssistProposal, AssistRequest, Capabilities, CheckResult, DiffOp, Knowledge, Lang, Op, ParamValue, ProposeDirectivesRequest, ProposeDirectivesResult, PutResult, RenderResult, SourceFile, TechTemplate } from './types'

// The UI does not know which core it talks to:
//  - ConnectCoreClient: the local `haro serve` (native Go), with the client
//    generated by buf from proto/haro/v1/haro.proto.
//  - WasmCoreClient: the same core compiled to WebAssembly for the public web,
//    with no server and without the configuration leaving the browser.
// A configuration can have one or several files, in load order.
export interface CoreClient {
  capabilities(): Promise<Capabilities>
  // `lang` is the language of the explanations and detector messages (default: English).
  analyze(files: SourceFile[], lang?: Lang): Promise<Analysis>
  apply(files: SourceFile[], ops: Op[]): Promise<ApplyResult>
  diff(before: string, after: string): Promise<DiffOp[]>
  check(files: SourceFile[]): Promise<CheckResult>
  getConfig(): Promise<SourceFile[] | null>
  putFile(path: string, text: string): Promise<PutResult>
  // Saves several files at once: the set is validated and everything or nothing is saved.
  putFiles(files: SourceFile[]): Promise<PutResult>
  knowledge(lang?: Lang): Promise<Knowledge>
  /** Complete per-technology templates, with their parameters in the requested language. */
  templates(lang?: Lang): Promise<TechTemplate[]>
  /**
   * Renders a template over the files: returns the operations and the result of
   * applying them (without writing). An invalid parameter is an Error with the
   * core's message in the requested language.
   */
  renderTemplate(files: SourceFile[], id: string, params: Record<string, ParamValue>, lang?: Lang): Promise<RenderResult>
  /**
   * Talks to the assistant (only with `haro serve --assistant`; see
   * capabilities().canAssist). The answer streams in; aborting `signal` cuts
   * the request. Errors are Errors carrying the server's message.
   */
  assist(req: AssistRequest, signal?: AbortSignal): AsyncIterable<AssistEvent>
  /**
   * Turns a description into directives for ONE section (unary, same availability
   * as assist). Nothing is applied. Errors carry the server's message.
   */
  proposeDirectives(req: ProposeDirectivesRequest, signal?: AbortSignal): Promise<ProposeDirectivesResult>
}

// RPC errors arrive as an Error with the server's message (without the
// «[code]» prefix of ConnectError) and the code in `code`.
function fail(e: unknown): never {
  const err = ConnectError.from(e)
  throw Object.assign(new Error(err.rawMessage), { code: err.code })
}

async function rpc<T>(p: Promise<T>): Promise<T> {
  try { return await p } catch (e) { fail(e) }
}

// Messages carry $typeName; the UI works with plain objects and stricter types
// (see types.ts). The core always fills in doc and topology.
const plain = <T>(m: unknown) => m as T

export class ConnectCoreClient implements CoreClient {
  private core: ReturnType<typeof createClient<typeof CoreService>>
  private config: ReturnType<typeof createClient<typeof ConfigService>>
  private assistant: ReturnType<typeof createClient<typeof AssistService>>

  constructor(baseUrl = '') {
    // JSON, not binary: same format as the contract messages and easy to debug.
    const transport = createConnectTransport({ baseUrl, useBinaryFormat: false })
    this.core = createClient(CoreService, transport)
    this.config = createClient(ConfigService, transport)
    this.assistant = createClient(AssistService, transport)
  }

  async *assist(req: AssistRequest, signal?: AbortSignal): AsyncGenerator<AssistEvent> {
    try {
      for await (const ev of this.assistant.assist(req, { signal })) {
        switch (ev.event.case) {
          case 'text': yield { type: 'text', text: ev.event.value }; break
          case 'proposal': yield { type: 'proposal', proposal: plain<AssistProposal>(ev.event.value) }; break
          case 'done': yield { type: 'done', done: plain<AssistDone>(ev.event.value) }; break
        }
      }
    } catch (e) { fail(e) }
  }

  async proposeDirectives(req: ProposeDirectivesRequest, signal?: AbortSignal) {
    return plain<ProposeDirectivesResult>(await rpc(this.assistant.proposeDirectives(req, { signal })))
  }

  async capabilities() { return plain<Capabilities>(await rpc(this.config.getCapabilities({}))) }
  async analyze(files: SourceFile[], lang: Lang = 'en') { return plain<Analysis>(await rpc(this.core.analyze({ files, lang }))) }
  async apply(files: SourceFile[], ops: Op[]) { return plain<ApplyResult>(await rpc(this.core.apply({ files, ops }))) }
  async diff(before: string, after: string) { return plain<DiffOp[]>((await rpc(this.core.diff({ before, after }))).ops) }
  async check(files: SourceFile[]) { return plain<CheckResult>(await rpc(this.core.check({ files }))) }
  async knowledge(lang: Lang = 'en') { return plain<Knowledge>(await rpc(this.core.getKnowledge({ lang }))) }

  // A parameter's default value arrives as google.protobuf.Value; the UI works
  // with its JSON (text, number, bool or list).
  async templates(lang: Lang = 'en') {
    const res = await rpc(this.core.listTemplates({ lang }))
    return res.templates.map(t => ({
      ...t,
      params: t.params.map(p => ({ ...p, defaultValue: p.defaultValue ? toJson(ValueSchema, p.defaultValue) : undefined })),
    })) as unknown as TechTemplate[]
  }

  async renderTemplate(files: SourceFile[], id: string, params: Record<string, ParamValue>, lang: Lang = 'en') {
    const values = Object.fromEntries(Object.entries(params).map(([k, v]) => [k, fromJson(ValueSchema, v)]))
    return plain<RenderResult>(await rpc(this.core.renderTemplate({ files, id, params: values, lang })))
  }

  async getConfig() {
    try { return plain<SourceFile[]>((await this.config.getConfig({})).files) }
    catch (e) {
      if (ConnectError.from(e).code === Code.NotFound) return null // haro serve without --file
      fail(e)
    }
  }

  putFile(path: string, text: string): Promise<PutResult> { return this.put({ path, text }) }
  putFiles(files: SourceFile[]): Promise<PutResult> { return this.put({ files }) }

  private async put(req: { path?: string; text?: string; files?: SourceFile[] }): Promise<PutResult> {
    try {
      const r = await this.config.putConfig(req)
      return {
        saved: r.saved,
        error: r.error || undefined,
        check: r.check ? plain<CheckResult>(r.check) : undefined,
        issue: r.issue ? plain<PutResult['issue']>(r.issue) : undefined,
        path: r.path || undefined,
      }
    } catch (e) {
      const err = ConnectError.from(e)
      return { saved: false, error: err.rawMessage, status: err.code === Code.PermissionDenied ? 403 : 400 }
    }
  }
}
